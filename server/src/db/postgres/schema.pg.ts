const TABLE_NAME_PATTERN = /CREATE TABLE IF NOT EXISTS ([a-z_0-9]+)/;

/**
 * Table names in the same FK-dependency order as POSTGRES_BASELINE_TABLES —
 * the single source of truth for "what order can I safely INSERT rows in"
 * (parents before children), used by the one-time import tool. Derived from
 * the DDL itself so it can never drift from the table list above.
 */
export function baselineTableNamesInDependencyOrder(): readonly string[] {
  return POSTGRES_BASELINE_TABLES.map((sql) => {
    const match = sql.match(TABLE_NAME_PATTERN);
    if (!match) throw new Error(`could not parse a table name out of: ${sql.slice(0, 80)}...`);
    return match[1];
  });
}
