/**
 * Postgres baseline schema — the Postgres-equivalent END STATE of
 * server/src/db/schema.ts + all 207 SQLite migration steps in
 * server/src/db/migrations.ts, produced by introspecting a live SQLite
 * instance's sqlite_master (after createTables + runMigrations) and
 * hand-translating the dialect differences. This is a BASELINE, not a
 * step-by-step transliteration of migrations.ts: SQLite-only workarounds
 * (e.g. the `PRAGMA foreign_keys=OFF` create-copy-drop-rename dance
 * migrations.ts uses to change a column's type, since SQLite has no
 * `ALTER COLUMN`) have no Postgres equivalent and are already resolved into
 * this end-state DDL directly — Postgres's native `ALTER TABLE ... ALTER
 * COLUMN` replaces that whole pattern going forward.
 *
 * Table order matters: unlike SQLite, Postgres requires a REFERENCES target
 * to already exist at CREATE TABLE time, so these are topologically sorted
 * by foreign-key dependency (verified by applying this file's DDL to a real
 * Postgres 17 instance end-to-end with zero errors — see
 * postgres-schema.test.ts).
 *
 * Type mapping decisions:
 *  - `INTEGER PRIMARY KEY AUTOINCREMENT` -> `INTEGER GENERATED BY DEFAULT AS
 *    IDENTITY PRIMARY KEY` — BY DEFAULT, not ALWAYS, deliberately: it accepts
 *    an explicit id on INSERT without needing `OVERRIDING SYSTEM VALUE`,
 *    exactly like SQLite's AUTOINCREMENT already does. This is load-bearing
 *    for the one-time import tool (migrate-sqlite-to-postgres.ts), which must
 *    preserve every row's original id so existing foreign keys still resolve;
 *    it costs nothing in normal operation because no application call site
 *    ever supplies an explicit id on insert today.
 *  - Boolean-flag columns stay INTEGER (0/1), not converted to BOOLEAN — this
 *    avoids touching every truthy-check read site in the same migration
 *    milestone that's already converting sync SQL calls to async.
 *  - `REAL` -> `DOUBLE PRECISION`, `BLOB` -> `BYTEA`.
 *  - Every column identified as a timestamp is `TIMESTAMPTZ`: an explicit
 *    SQLite `DATETIME` column (`DEFAULT CURRENT_TIMESTAMP` -> `DEFAULT
 *    now()`), an INTEGER column defaulted via `strftime('%s','now')`
 *    (epoch seconds — only `idempotency_keys.created_at`), a TEXT column
 *    defaulted via `datetime('now')` (a handful of `plugin_*` audit/cache
 *    tables), or an INTEGER column hand-verified (by reading its writer in
 *    src/nest/**) to hold epoch MILLISECONDS despite no SQL-level default —
 *    see EPOCH_MS_COLUMNS in the generation notes below. Those millisecond
 *    columns get no DB-level DEFAULT here, matching today's behavior where
 *    the app always supplies `Date.now()` explicitly on insert.
 *  - A handful of TEXT columns are known to sometimes hold an
 *    application-generated ISO-8601 string (e.g. oauth.service.ts,
 *    trip-invite.service.ts) but could not be positively identified from the
 *    DDL alone across all ~390 TEXT columns in this schema — those are
 *    conservatively left as TEXT rather than guessed at. Storing an ISO
 *    string in TEXT is correct and loses no data; it just isn't natively
 *    TIMESTAMPTZ-typed yet. A follow-up per-column audit can promote specific
 *    columns later without a data migration (TEXT and TIMESTAMPTZ round-trip
 *    the same ISO representation).
 *
 * Columns hand-verified to hold epoch MILLISECONDS (declared INTEGER in
 * SQLite, TIMESTAMPTZ here): google_place_photo_meta.{fetched_at,error_at},
 * journey_contributors.added_at, journey_entries.{created_at,updated_at},
 * journey_entry_photos.created_at, journey_photos.created_at,
 * journey_trips.added_at, journeys.{created_at,updated_at},
 * place_details_cache.fetched_at, plugin_oauth_state.created_at,
 * plugin_oauth_tokens.expires_at, plugin_scheduled_tasks.due_at,
 * trek_photo_cache_meta.fetched_at, user_notice_dismissals.dismissed_at,
 * webauthn_challenges.expires_at. idempotency_keys.created_at is the one
 * exception stored in epoch SECONDS (`strftime('%s','now')`) rather than
 * milliseconds — also TIMESTAMPTZ here. The one-time import tool
 * (migrate-sqlite-to-postgres.ts) is what actually reconciles the stored
 * values into real timestamps; this file only declares the target column
 * types.
 *
 * `migrations` (near the middle of the list below) is a vestigial fossil
 * table — a SQLite CREATE-TABLE DDL literally matching TypeORM's default
 * migrations-table shape, left over from an early prototype. It is
 * write-only (one seed INSERT in migrations.ts, never read by any app code)
 * and carried through here unchanged for schema fidelity, not because
 * anything depends on it.
 *
 * One table from the live introspection is DELIBERATELY excluded:
 * `schema_version`. In SQLite it tracks the OLD migration system's own
 * bookkeeping (which of the 207 steps in migrations.ts have run) — that
 * number is meaningless once the app runs on Postgres, and re-creating it
 * here would collide with migrations.pg.ts's own `schema_version` table
 * (which tracks *this* file's PG_MIGRATIONS array instead, starting fresh at
 * the baseline). The one-time import tool does not copy this table's row.
 */

